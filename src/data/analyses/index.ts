export interface Competitor {
  /** 公司简称 */
  name: string;
  /** 证券代码（可空） */
  code?: string;
  /** 对比要点：规模、份额、业务重叠、相对优劣势 */
  note: string;
}

/** 观点/要点条目 */
export interface ViewPoint {
  /** 要点标题（短句） */
  point: string;
  /** 展开说明，含真实数据或机构观点 */
  detail: string;
}

export interface PreAnalysis {
  businessSnapshot?: {
    summary: string | null; scope: string | null; industry: string | null;
    review: string | null; reviewDate: string | null; source: string;
    groups: { label: string; date: string | null; items: { name: string; income: number | null; incomeRatio: number | null; profitRatio: number | null; grossMargin: number | null }[] }[];
  };
  code: string;
  /** Explicitly separate sourced research drafts from reviewed legacy content. */
  researchStatus?: 'draft' | 'reviewed';
  viewBasis?: 'research_hypotheses' | 'institutional_views';
  sources?: { id: string; label: string; url: string; kind: 'issuer' | 'disclosure' | 'aggregate'; retrievedAt: string }[];
  verificationTasks?: string[];
  /** 公司全称 */
  fullName?: string;
  /** 所属行业（含层级） */
  industry: string;
  /** 公司地位一句话 */
  position?: string;

  /** 深度解析正文：多段，每段一个主题，段间用 \n\n 分隔 */
  summary: string;

  /** 核心优势/护城河要点 */
  moat?: ViewPoint[];
  /** 主要竞争对手 */
  competitors?: Competitor[];

  /** 市场看好（多头）主流观点 */
  bullCase?: ViewPoint[];
  /** 市场不看好/分歧（空头）观点 */
  bearCase?: ViewPoint[];

  /** 评级分布 */
  ratingSummary?: { buy: number; hold: number; sell: number };
  /** 目标价区间（元） */
  targetPriceRange?: { min: number; max: number };

  /** 数据来源 */
  source: string;
  /** 生成日期 */
  generatedAt: string;
}


